"""Reproducible dependency-free packager. Run from any directory with Python 3.10+."""
from __future__ import annotations
import hashlib
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.1.0"


def encode(value):
    if value is None:
        return b"z"
    if value is True:
        return b"t"
    if value is False:
        return b"f"
    if isinstance(value, (str, bytes)):
        data = value.encode("utf-8") if isinstance(value, str) else value
        return b"s" + str(len(data)).encode() + b":" + data
    if isinstance(value, int):
        data = str(value).encode()
        return b"n" + str(len(data)).encode() + b":" + data
    if isinstance(value, list):
        value = dict(enumerate(value, 1))
    if isinstance(value, dict):
        pairs = sorted((encode(k), encode(v)) for k, v in value.items())
        return b"m" + str(len(pairs)).encode() + b":" + b"".join(k + v for k, v in pairs)
    raise TypeError(type(value))


def quote(data: str) -> str:
    for n in range(20):
        eq = "=" * n
        if "]" + eq + "]" not in data:
            # A newline after the bracket is consumed by Lua, preserving first bytes.
            return "[" + eq + "[\n" + data + "]" + eq + "]"
    raise ValueError("Cannot quote source")


def build():
    files = {}
    for path in sorted((ROOT / "src").rglob("*.lua")):
        # Normalize line endings so Windows checkout and Linux CI generate identical hashes.
        files[path.relative_to(ROOT / "src").as_posix()] = path.read_text(encoding="utf-8").replace("\r\n", "\n").encode()
    fingerprint = hashlib.sha256(b"".join(k.encode() + b"\0" + v for k, v in files.items())).hexdigest()[:12]
    manifest = {"schema": 1, "version": VERSION, "release": f"{VERSION}-{fingerprint}", "files": [
        {"path": k, "size": len(v), "sha256": hashlib.sha256(v).hexdigest()} for k, v in files.items()
    ]}
    data = encode(manifest)
    (ROOT / "manifest.dat").write_bytes(data)
    boot_modules = ["core.codec", "core.crypto", "core.storage", "core.hardware", "core.config", "core.updater", "core.installer"]
    bootstrap = ["-- Generated by tools/build.py. Edit src/, then rebuild. Lua 5.2/5.3 / OpenOS.\n", "local sources={}\n"]
    for module in boot_modules:
        code = files[module.replace(".", "/") + ".lua"].decode()
        bootstrap.append(f"sources[ {quote(module)} ]={quote(code)}\n")
    # OpenOS require does NOT implement standard Lua package.preload/searchers.
    # Bootstrap modules use a private lexical require; global module caches stay intact.
    bootstrap.append('local nativeRequire=require\nlocal cache={}\nlocal bootstrapRequire\n'
                     'bootstrapRequire=function(name)\n  if cache[name]~=nil then return cache[name] end\n'
                     '  if not sources[name] then return nativeRequire(name) end\n'
                     '  local env=setmetatable({require=bootstrapRequire},{__index=_ENV})\n'
                     '  local value=assert(load(sources[name],"=installer/"..name,"t",env))(name)\n'
                     '  cache[name]=value\n  return value\nend\n')
    prefix = "".join(bootstrap)
    def finish(invocation):
        return ('local args={...}\nlocal ok,err=xpcall(function() '+invocation+' end,debug.traceback)\nassert(ok,err)\n')
    (ROOT / "install.lua").write_text(prefix + finish('bootstrapRequire("core.installer").main(args)'), encoding="utf-8", newline="\n")
    offline = [prefix, "local payload={}\n"]
    for path, content in {"manifest.dat": data, **{"src/"+k: v for k, v in files.items()}}.items():
        offline.append(f"payload[ {quote(path)} ]={quote(content.decode())}\n")
    offline.append(finish('bootstrapRequire("core.installer").main(args,payload)'))
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    offline_path = dist / "factoryos-offline.lua"
    offline_path.write_text("".join(offline), encoding="utf-8", newline="\n")
    archive = dist / f"FactoryOS-{VERSION}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        candidates = [ROOT / "install.lua", ROOT / "manifest.dat", ROOT / "README.md", offline_path]
        candidates += list((ROOT / "src").rglob("*.lua")) + list((ROOT / "docs").glob("*.md"))
        candidates += list((ROOT / "tools").glob("*.py")) + list((ROOT / "tools").glob("*.lua"))
        candidates += list((ROOT / "tests").glob("*.py")) + list((ROOT / "tests").glob("*.lua"))
        candidates += [ROOT / ".gitignore", ROOT / "requirements-dev.txt"]
        for path in sorted(candidates):
            if path.exists():
                info = zipfile.ZipInfo("FactoryOS/" + path.relative_to(ROOT).as_posix(), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, path.read_bytes().replace(b"\r\n", b"\n"))
    print(f"Built {manifest['release']}: {len(files)} modules, {sum(map(len, files.values()))} source bytes")
    print(archive)
    return manifest


if __name__ == "__main__":
    build()
